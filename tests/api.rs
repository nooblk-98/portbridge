#![allow(dead_code)]

mod common;

use axum::http::{Method, StatusCode};
use common::{api_request, api_request_raw, client, with_options, Setup};
use portbridge::storage::Storage;
use serde_json::json;

const ROUTE: &str = "192.168.50.10/32";

fn seeded() -> Setup {
    let setup = Setup::new();
    setup.seed_keys();
    let owner = with_options(
        client("owner", "10.8.0.2", "owner-public"),
        json!({"advertised_routes": [ROUTE]}),
    );
    setup.store(&[
        owner,
        with_options(
            client("reader", "10.8.0.3", "reader-public"),
            json!({"split_tunnel": true}),
        ),
        with_options(
            client("third", "10.8.0.4", "third-public"),
            json!({"split_tunnel": true}),
        ),
    ]);
    setup
}

#[tokio::test]
async fn login_issues_session_and_remember_cookies() {
    let setup = seeded();
    let app = setup.router();
    let (status, headers, body) = api_request(
        app.clone(),
        Method::POST,
        "/auth/login",
        None,
        Some(json!({"password": "test-password"})),
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(body, "{\"status\":\"ok\"}\n");
    let cookies: Vec<String> = headers
        .get_all("set-cookie")
        .iter()
        .map(|value| value.to_str().unwrap().to_string())
        .collect();
    assert_eq!(cookies.len(), 2);
    assert!(cookies.iter().any(|cookie| cookie.starts_with("session=")));
    assert!(cookies
        .iter()
        .any(|cookie| cookie.starts_with("remember_token=")));
    assert!(cookies.iter().all(|cookie| cookie.contains("HttpOnly")));
    assert!(cookies.iter().all(|cookie| cookie.contains("SameSite=Lax")));

    let session = cookies
        .iter()
        .find(|cookie| cookie.starts_with("session="))
        .unwrap()
        .split(';')
        .next()
        .unwrap()
        .trim_start_matches("session=");
    let (status, _, body) =
        api_request(app, Method::GET, "/api/clients", Some(session), None).await;
    assert_eq!(status, StatusCode::OK);
    assert!(body.contains("\"name\":\"owner\""));
}

#[tokio::test]
async fn wrong_password_and_rate_limit_are_reported() {
    let setup = seeded();
    let app = setup.router();
    for attempt in 0..5 {
        let (status, _, body) = api_request(
            app.clone(),
            Method::POST,
            "/auth/login",
            None,
            Some(json!({"password": "wrong"})),
        )
        .await;
        assert_eq!(status, StatusCode::UNAUTHORIZED, "attempt {attempt}");
        assert_eq!(body, "{\"error\":\"Invalid password\"}\n");
    }
    let (status, _, body) = api_request(
        app,
        Method::POST,
        "/auth/login",
        None,
        Some(json!({"password": "test-password"})),
    )
    .await;
    assert_eq!(status, StatusCode::TOO_MANY_REQUESTS);
    assert!(body.contains("Too many login attempts"));
}

#[tokio::test]
async fn protected_routes_require_a_valid_session() {
    let setup = seeded();
    let app = setup.router();
    let (status, _, body) = api_request(app.clone(), Method::GET, "/api/state", None, None).await;
    assert_eq!(status, StatusCode::UNAUTHORIZED);
    assert_eq!(body, "{\"description\":\"Unauthorized\"}\n");

    let (status, headers, _) = api_request(app.clone(), Method::GET, "/", None, None).await;
    assert_eq!(status, StatusCode::FOUND);
    assert_eq!(headers.get("location").unwrap(), "/login?next=/");

    let (status, _, body) = api_request(app, Method::GET, "/login", None, None).await;
    assert_eq!(status, StatusCode::OK);
    assert!(body.contains("loginApp()"));
}

