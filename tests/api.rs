#[tokio::test]
async fn options_patch_accepts_route_access_and_rejects_bad_input() {
    let setup = seeded();
    let app = setup.router();
    let cookie = setup.cookie();
    let (status, _, body) = api_request(
        app.clone(),
        Method::PATCH,
        "/api/clients/owner/options",
        Some(&cookie),
        Some(json!({
            "advertised_routes": [ROUTE],
            "route_access": {ROUTE: ["reader-public"]}
        })),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert!(body.contains("\"route_access\":{\"192.168.50.10/32\":[\"reader-public\"]}"));
    let (status, _, body) = api_request(
        app.clone(),
        Method::GET,
        "/api/clients",
        Some(&cookie),
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    let payload: serde_json::Value = serde_json::from_str(&body).unwrap();
    assert_eq!(
        payload["routes"][0]["allowed_peer_public_keys"],
        json!(["reader-public"])
    );

    let (status, _, body) = api_request(
        app,
        Method::PATCH,
        "/api/clients/owner/options",
        Some(&cookie),
        Some(json!({"advertised_routes": [ROUTE], "route_access": {ROUTE: ["ghost"]}})),
    )
    .await;
    assert_eq!(status, StatusCode::BAD_REQUEST);
    assert!(body.contains("unknown peer"));
}

#[tokio::test]
async fn client_crud_and_config_download_work() {
    let setup = seeded();
    let app = setup.router();
    let cookie = setup.cookie();
    let (status, _, body) = api_request(
        app.clone(),
        Method::POST,
        "/api/clients",
        Some(&cookie),
        Some(json!({"name": "laptop", "address": "10.8.0.9"})),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert!(body.contains("\"name\":\"laptop\""));
    assert!(setup.storage.exists(
        &setup
            .config
            .clients_dir
            .join("laptop.conf")
            .to_string_lossy()
    ));

    let (status, _, body) = api_request(
        app.clone(),
        Method::PATCH,
        "/api/clients/laptop",
        Some(&cookie),
        Some(json!({"name": "laptop-renamed"})),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert!(setup.storage.exists(
        &setup
            .config
            .clients_dir
            .join("laptop-renamed.conf")
            .to_string_lossy()
    ));

    let (status, headers, body) = api_request(
        app.clone(),
        Method::GET,
        "/clients/laptop-renamed.conf",
        Some(&cookie),
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert!(body.contains("[Interface]"));
    assert!(headers
        .get("content-disposition")
        .unwrap()
        .to_str()
        .unwrap()
        .contains("laptop-renamed.conf"));

    let (status, headers, body) = api_request_raw(
        app.clone(),
        Method::GET,
        "/clients/laptop-renamed.png",
        Some(&cookie),
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(headers.get("content-type").unwrap(), "image/png");
    assert!(body.starts_with(b"\x89PNG\r\n\x1a\n"));

    let (status, _, _) = api_request(
        app,
        Method::DELETE,
        "/api/clients/laptop-renamed",
        Some(&cookie),
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert!(!setup.storage.exists(
        &setup
            .config
            .clients_dir
            .join("laptop-renamed.conf")
            .to_string_lossy()
    ));
}

#[tokio::test]
async fn forwarding_rules_round_trip_through_the_api() {
    let setup = seeded();
    let app = setup.router();
    let cookie = setup.cookie();
    let (status, _, body) = api_request(
        app.clone(),
        Method::POST,
        "/api/forwardings",
        Some(&cookie),
        Some(json!({
            "port": 30001,
            "protocol": "tcp",
            "client_ip": "10.8.0.3",
            "target_port": 8081
        })),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    let (_status, _, body) = api_request(
        app.clone(),
        Method::GET,
        "/api/forwardings",
        Some(&cookie),
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    let payload: serde_json::Value = serde_json::from_str(&body).unwrap();
    assert_eq!(payload["items"][0]["port"], 30001);
    assert_eq!(payload["items"][0]["peer_public_key"], "reader-public");
    let (status, _, _) = api_request(
        app,
        Method::DELETE,
        "/api/forwardings/30001/tcp",
        Some(&cookie),
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK);
}

